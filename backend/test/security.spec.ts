// Generated by Python: bcrypt.hashpw(b'Secret123', bcrypt.gensalt(4)).decode()
const PY_HASH = '$2b$04$80.XhJV.OAtTXnJLKDeR/.qgFANlWWR4Kfg8lMI0h2SfRGCtb8aGW';

function req(headers: Record<string, string>): Request {
  const lower: Record<string, string> = {};
  for (const [k, v] of Object.entries(headers)) lower[k.toLowerCase()] = v;
  return { headers: lower } as unknown as Request;
}

/** Route the scope queries a user row and group lookups would make. */
function fakeDb(user: Record<string, unknown> | null, groups: { userGroups?: number[]; extGroups?: number[]; agents?: string[]; queues?: string[] } = {}) {
  queryOne.mockImplementation(async (sql: string) => {
    if (sql.includes('OpDesk_settings')) return null;
    if (sql.includes('FROM users')) return user;
    return null;
  });
  query.mockImplementation(async (sql: string) => {
    if (sql.includes('user_monitor_modes')) return [{ mode: 'listen' }, { mode: 'whisper' }];
    if (sql.includes('UNION')) return [...(groups.userGroups || []), ...(groups.extGroups || [])].map((g) => ({ group_id: g }));
    if (sql.startsWith('SELECT group_id FROM user_groups')) return (groups.userGroups || []).map((g) => ({ group_id: g }));
    if (sql.startsWith('SELECT group_id FROM group_agents')) return (groups.extGroups || []).map((g) => ({ group_id: g }));
    if (sql.includes('FROM group_agents WHERE group_id IN')) return (groups.agents || []).map((a) => ({ agent_ext: a }));
    if (sql.includes('FROM group_queues')) return (groups.queues || []).map((q) => ({ extension: q }));
    return [];
  });
}

beforeEach(() => {
  query.mockReset();
  queryOne.mockReset();
  execute.mockReset();
  resetJwtSecretCache();
  process.env.JWT_SECRET = 'test-secret';
});

describe('JWT', () => {
  it('round-trips with the PyJWT header and claims', async () => {
    fakeDb(null);
    const token = await createAccessToken({ id: 7, username: 'alice', role: 'agent' });
    const [h] = token.split('.');
    expect(JSON.parse(Buffer.from(h, 'base64url').toString())).toEqual({ alg: 'HS256', typ: 'JWT' });
    const claims = await decodeAccessToken(token);
    expect(claims).toMatchObject({ sub: '7', username: 'alice', role: 'agent' });
    expect((claims!.exp as number) - (claims!.iat as number)).toBe(24 * 3600);
  });

  it('matches an independent HS256 signature (what PyJWT computes)', () => {
    const header = Buffer.from('{"alg":"HS256","typ":"JWT"}').toString('base64url');
    const body = Buffer.from('{"sub":"1","exp":9999999999}').toString('base64url');
    const sig = crypto.createHmac('sha256', 'k').update(`${header}.${body}`).digest('base64url');
    expect(decodeJwt(`${header}.${body}.${sig}`, 'k')).toEqual({ sub: '1', exp: 9999999999 });
  });

  it('rejects a wrong secret, an expired token, tampering and alg none', () => {
    const t = encodeJwt({ sub: '1', exp: Math.floor(Date.now() / 1000) + 60 }, 'a');
    expect(decodeJwt(t, 'b')).toBeNull();
    expect(decodeJwt(encodeJwt({ sub: '1', exp: Math.floor(Date.now() / 1000) - 1 }, 'a'), 'a')).toBeNull();
    const [h, , s] = t.split('.');
    expect(decodeJwt(`${h}.${Buffer.from('{"sub":"2"}').toString('base64url')}.${s}`, 'a')).toBeNull();
    const none = `${Buffer.from('{"alg":"none"}').toString('base64url')}.${Buffer.from('{"sub":"1"}').toString('base64url')}.`;
    expect(decodeJwt(none, 'a')).toBeNull();
    expect(decodeJwt('garbage', 'a')).toBeNull();
  });

  it('prefers the DB JWT_SECRET over the env one', async () => {
    queryOne.mockResolvedValue({ setting_value: 'db-secret' });
    const token = await createAccessToken({ id: 1, username: 'a', role: 'admin' });
    expect(decodeJwt(token, 'db-secret')).not.toBeNull();
    expect(decodeJwt(token, 'test-secret')).toBeNull();
  });

  it('getCurrentUser: 401 missing / invalid / non-int sub / deleted or inactive user', async () => {
    fakeDb({ id: 3, username: 'bob', extension: '101', name: 'Bob', role: 'agent', is_active: 1 });
    await expect(getCurrentUser(req({}))).rejects.toMatchObject({ status: 401, detail: 'Not authenticated' });
    await expect(getCurrentUser(req({ Authorization: 'Bearer nope' }))).rejects.toMatchObject({ status: 401, detail: 'Invalid or expired token' });
    const weird = encodeJwt({ sub: 'abc', username: 'x', exp: Math.floor(Date.now() / 1000) + 60 }, 'test-secret');
    await expect(getCurrentUser(req({ Authorization: `Bearer ${weird}` }))).rejects.toMatchObject({ status: 401 });

    const token = await createAccessToken({ id: 3, username: 'bob', role: 'agent' });
    const p = await getCurrentUser(req({ Authorization: `bearer ${token}` }));
    expect(p).toMatchObject({ id: 3, username: 'bob', name: 'Bob', role: 'agent', extension: '101', allowed_agent_extensions: ['101'] });

    fakeDb({ id: 3, username: 'bob', extension: '101', name: 'Bob', role: 'agent', is_active: 0 });
    await expect(getCurrentUser(req({ Authorization: `Bearer ${token}` }))).rejects.toMatchObject({ status: 401 });
    fakeDb(null);
    expect(await authenticateWsToken(token)).toBeNull();
  });

  it('an API key on a JWT-only route fails as an invalid token', async () => {
    fakeDb(null);
    await expect(getCurrentUser(req({ Authorization: `Bearer ${generateApiKey()}` }))).rejects.toMatchObject({ status: 401, detail: 'Invalid or expired token' });
  });
});

describe('bcrypt', () => {
  it('verifies a hash written by Python bcrypt, in either argument order', async () => {
    expect(await verifyPassword('Secret123', PY_HASH)).toBe(true);
    expect(await verifyPassword('secret123', PY_HASH)).toBe(false);
    expect(await verifyUserPassword(PY_HASH, 'Secret123')).toBe(true);
    expect(await verifyPassword('', PY_HASH)).toBe(false);
    expect(await verifyPassword('x', 'not-a-hash')).toBe(false);
  });

  it('hashes in the $2b$ format', async () => {
    const h = await hashPassword('pw-12345');
    expect(h).toMatch(/^\$2b\$12\$/);
    expect(await verifyPassword('pw-12345', h)).toBe(true);
  }, 20000);
});

describe('API keys', () => {
  it('opd_ + 40 hex, SHA-256 hex hash, extension-config:read and the contacts scopes offered', () => {
    const k = generateApiKey();
    expect(k).toMatch(/^opd_[0-9a-f]{40}$/);
    expect(hashApiKey('opd_x')).toBe(crypto.createHash('sha256').update('opd_x').digest('hex'));
    expect(ALL_PERMISSIONS).toEqual([
      'calls:read',
      'calls:write',
      'cdr:read',
      'analytics:read',
      'extension-config:read',
      'contacts:read',
      'contacts:write',
    ]);
  });

  it('is read from X-API-Key or a Bearer opd_ token', () => {
    expect(extractApiKey(req({ 'X-API-Key': ' opd_a ' }))).toBe('opd_a');
    expect(extractApiKey(req({ Authorization: 'Bearer opd_b' }))).toBe('opd_b');
    expect(extractApiKey(req({ Authorization: 'Bearer eyJ...' }))).toBeNull();
  });

  it('requireScope: 401 unknown key, 403 missing scope, admin-equivalent principal otherwise', async () => {
    queryOne.mockResolvedValueOnce(null);
    await expect(requireScope(req({ 'X-API-Key': 'opd_zz' }), 'cdr:read')).rejects.toMatchObject({ status: 401, detail: 'Invalid or expired API key' });
    queryOne.mockResolvedValueOnce({ id: 4, name: 'crm', key_prefix: 'opd_12345678', scopes: '["calls:read"]', enabled: 1 });
    await expect(requireScope(req({ 'X-API-Key': 'opd_zz' }), 'cdr:read')).rejects.toMatchObject({
      status: 403,
      detail: 'API key missing required scope: cdr:read',
    });
    queryOne.mockResolvedValueOnce({ id: 4, name: 'crm', key_prefix: 'opd_12345678', scopes: '["cdr:read"]', enabled: 1 });
    const p = await requireScope(req({ 'X-API-Key': 'opd_zz' }), 'cdr:read');
    expect(p).toMatchObject({ id: null, username: 'apikey:crm', role: 'admin', api_key: true, api_key_id: 4, allowed_agent_extensions: null, live_agent_extensions: null });
    expect(execute).toHaveBeenCalledWith('UPDATE api_keys SET last_used_at = NOW() WHERE id = ?', [4]);
  });
});

describe('login limiter', () => {
  beforeEach(() => resetLoginLimiter());

  it('locks an IP after 10 failures with 429 + Retry-After, success clears it', () => {
    for (let i = 0; i < 9; i++) {
      checkLoginRateLimit('1.2.3.4');
      recordLoginFailure('1.2.3.4');
    }
    expect(() => checkLoginRateLimit('1.2.3.4')).not.toThrow();
    recordLoginFailure('1.2.3.4');
    let err: unknown;
    try {
      checkLoginRateLimit('1.2.3.4');
    } catch (e) {
      err = e;
    }
    expect(err).toBeInstanceOf(HttpError);
    const h = err as HttpError;
    expect(h.status).toBe(429);
    expect(String(h.detail)).toMatch(/^Too many failed login attempts\. Try again in (599|600)s\.$/);
    expect(h.headers?.['Retry-After']).toMatch(/^(599|600)$/);
    expect(() => checkLoginRateLimit('5.6.7.8')).not.toThrow();
    clearLoginFailures('1.2.3.4');
    expect(() => checkLoginRateLimit('1.2.3.4')).not.toThrow();
  });
});

describe('getUserScope', () => {
  it('agent: history = own extension, live = own + group agents and queues', async () => {
    fakeDb({ id: 5, username: 'ag', extension: '101', name: null, role: 'agent', is_active: 1 }, { extGroups: [2], agents: ['101', '102', '103'], queues: ['600'] });
    const s = await getUserScope(5);
    expect(s.allowed_agent_extensions).toEqual(['101']);
    expect(s.allowed_queue_names).toEqual([]);
    expect(s.live_agent_extensions).toEqual(['101', '102', '103']);
    expect(s.live_queue_names).toEqual(['600']);
    expect(s.monitor_modes).toEqual([]);
  });

  it('supervisor: both scopes are the groups of the account', async () => {
    fakeDb({ id: 6, username: 'sup', extension: '200', name: 'S', role: 'supervisor', is_active: 1 }, { userGroups: [1], agents: ['101'], queues: ['600'] });
    const s = await getUserScope(6);
    expect(s.allowed_agent_extensions).toEqual(['101']);
    expect(s.live_agent_extensions).toEqual(['101']);
    expect(s.allowed_queue_names).toEqual(['600']);
    expect(s.monitor_modes).toEqual(['listen', 'whisper']);
  });

  it('admin: unrestricted', async () => {
    fakeDb({ id: 1, username: 'admin', extension: null, name: null, role: 'admin', is_active: 1 });
    const s = await getUserScope(1);
    expect([s.allowed_agent_extensions, s.allowed_queue_names, s.live_agent_extensions, s.live_queue_names]).toEqual([null, null, null, null]);
  });

  it('the principal of an agent has no supervision modes; a supervisor with none granted can listen', async () => {
    fakeDb({ id: 5, username: 'ag', extension: '101', name: null, role: 'agent', is_active: 1 }, { extGroups: [2], agents: ['101'], queues: [] });
    expect(principalFromScope(await getUserScope(5)).monitor_modes).toEqual([]);
    fakeDb({ id: 6, username: 'sup', extension: '200', name: 'S', role: 'supervisor', is_active: 1 }, { userGroups: [1], agents: ['101'], queues: [] });
    const sup = await getUserScope(6);
    expect(principalFromScope(sup).monitor_modes).toEqual(['listen', 'whisper']);
    expect(principalFromScope({ ...sup, monitor_modes: [] }).monitor_modes).toEqual(['listen']);
  });

  it('missing user: the Python fallback, flagged as not existing', async () => {
    fakeDb(null);
    const s = await getUserScope(99);
    expect(s).toMatchObject({ exists: false, role: 'supervisor', allowed_agent_extensions: [] });
  });
});
